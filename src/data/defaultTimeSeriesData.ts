export interface TimeSeriesDataPoint {
  Time: number; // 1 to 96
  Rload: number; // Residential multiplier
  Iload: number; // Industrial multiplier
  Cload: number; // Commercial multiplier
}

/** Converts a 1-based 15-minute interval index (1-96) into a 24h clock string (e.g. 1 -> "00:15", 96 -> "24:00") */
export function timeIndexToClock(index: number): string {
  const totalMinutes = index * 15;
  const hours = Math.floor(totalMinutes / 60);
  const minutes = totalMinutes % 60;
  return `${String(hours).padStart(2, '0')}:${String(minutes).padStart(2, '0')}`;
}

